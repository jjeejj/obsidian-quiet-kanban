'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const sourceRoot = path.join(root, 'src');

// Source modules use literal CommonJS imports. Discover local dependencies
// recursively and preserve module scopes and Node's cache semantics in one file.
function bundle(entry) {
  const modules = new Map();
  function visit(filename) {
    const id = path.relative(root, filename).split(path.sep).join('/');
    if (modules.has(id)) return id;
    const source = fs.readFileSync(filename, 'utf8');
    const dependencies = {};
    modules.set(id, { source, dependencies });
    for (const match of source.matchAll(/\brequire\(\s*(['"])([^'"\r\n]+)\1\s*\)/g)) {
      const request = match[2];
      if (!request.startsWith('.')) {
        if (request !== 'obsidian') throw Error(`Unsupported external dependency in ${id}: ${request}`);
        continue;
      }
      const resolved = path.resolve(path.dirname(filename), request);
      if (!resolved.startsWith(sourceRoot + path.sep) || path.extname(resolved) !== '.cjs') {
        throw Error(`Local imports must resolve to a .cjs file under src: ${id} -> ${request}`);
      }
      dependencies[request] = visit(resolved);
    }
    return id;
  }
  const entryId = visit(entry);
  const factories = [...modules].map(([id, { source, dependencies }]) =>
    `${JSON.stringify(id)}: [function(module, exports, require) {\n${source}\n}, ${JSON.stringify(dependencies)}]`
  ).join(',\n');
  return `// Quiet Kanban — generated by npm run build.
'use strict';
const factories = {
${factories}
};
const cache = Object.create(null);
function load(id) {
  if (Object.hasOwn(cache, id)) return cache[id].exports;
  const [factory, dependencies] = factories[id];
  const module = { exports: {} };
  cache[id] = module;
  try {
    factory(module, module.exports, request => {
      if (Object.hasOwn(dependencies, request)) return load(dependencies[request]);
      if (request === 'obsidian') return require(request);
      throw Error('Unknown bundled dependency: ' + id + ' -> ' + request);
    });
  } catch (error) {
    delete cache[id];
    throw error;
  }
  return module.exports;
}
module.exports = load(${JSON.stringify(entryId)});
`;
}

if (require.main === module) {
  // The complete bundle is syntax-checked before replacing the installable file.
  const output = bundle(path.join(sourceRoot, 'main.cjs'));
  execFileSync(process.execPath, ['--check'], { input: output });
  fs.writeFileSync(path.join(root, 'main.js'), output);
  console.log('Built main.js (local modules bundled; obsidian supplied by the host)');
}
module.exports = { bundle };
